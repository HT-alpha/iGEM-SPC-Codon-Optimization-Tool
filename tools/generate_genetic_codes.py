#!/usr/bin/env python3
"""Generate the vendored NCBI genetic code tables for `cf-types`.

Ticket P1-05. Run:

    python3 tools/generate_genetic_codes.py

Output: crates/cf-types/data/genetic_codes.json

WHY GENERATE RATHER THAN TRANSCRIBE. There are 27 defined NCBI translation
tables, each 64 codons wide, plus per-table start and stop codon sets. Hand
transcription is ~1900 characters of data in which a single-character error
would silently mistranslate one codon in one organism class. Biopython vendors
the NCBI tables and is BSD-3-Clause, so it is usable as a build-time data
source; it is not a runtime dependency of `cf-types`.

CODON INDEXING. Output is indexed by the convention fixed in
planning/02-schemas/sequence.schema.json:

    index = 16*b0 + 4*b1 + b2,  with A=0, C=1, G=2, T=3

so `aa[i]` is the amino acid for the codon whose index is `i`. Storing the
table already permuted into index order means the Rust side never has to do
the permutation at load time, and a mistake in the permutation shows up in
`TST-CORE-002` rather than in a translated protein.

REPRODUCIBILITY. The generated file records the Biopython version it came
from. `TST-CORE-002` re-derives a spot-check set independently of Biopython so
that a Biopython upgrade cannot silently change the tables.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

try:
    import Bio
    from Bio.Data import CodonTable
except ImportError:  # pragma: no cover
    sys.exit("biopython is required to regenerate the tables: pip install biopython")

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "cf-types" / "data" / "genetic_codes.json"

BASES = "ACGT"  # index order: A=0, C=1, G=2, T=3


def codon_for_index(i: int) -> str:
    return BASES[(i >> 4) & 3] + BASES[(i >> 2) & 3] + BASES[i & 3]


def index_for_codon(codon: str) -> int:
    return 16 * BASES.index(codon[0]) + 4 * BASES.index(codon[1]) + BASES.index(codon[2])


def main() -> int:
    tables: dict[str, dict] = {}

    for table_id in sorted(CodonTable.unambiguous_dna_by_id):
        t = CodonTable.unambiguous_dna_by_id[table_id]

        aa = []
        for i in range(64):
            codon = codon_for_index(i)
            if codon in t.stop_codons:
                aa.append("*")
            else:
                residue = t.forward_table.get(codon)
                if residue is None:
                    sys.exit(f"table {table_id}: codon {codon} has no assignment")
                aa.append(residue)

        # Sanity: every codon assigned exactly once, and the stop set matches.
        derived_stops = {codon_for_index(i) for i, a in enumerate(aa) if a == "*"}
        if derived_stops != set(t.stop_codons):
            sys.exit(f"table {table_id}: stop set mismatch")

        tables[str(table_id)] = {
            "id": table_id,
            "name": t.names[0],
            "aliases": [n for n in t.names[1:] if n],
            "aa": "".join(aa),
            "starts": sorted(t.start_codons),
            "stops": sorted(t.stop_codons),
        }

    doc = {
        "$comment": (
            "Generated by tools/generate_genetic_codes.py - do not edit by hand. "
            "aa is indexed by index = 16*b0 + 4*b1 + b2 with A=0, C=1, G=2, T=3."
        ),
        "source": "NCBI genetic codes via Biopython Bio.Data.CodonTable",
        "biopython_version": Bio.__version__,
        "index_convention": "16*b0 + 4*b1 + b2; A=0, C=1, G=2, T=3",
        "defined_ids": sorted(int(k) for k in tables),
        "undefined_ids_in_range_1_33": [i for i in range(1, 34) if str(i) not in tables],
        "tables": tables,
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  tables defined      : {len(tables)}")
    print(f"  ids                 : {doc['defined_ids']}")
    print(f"  undefined in 1..33  : {doc['undefined_ids_in_range_1_33']}")
    print(f"  biopython           : {Bio.__version__}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
